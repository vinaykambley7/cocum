// Helper to create empty report for a staff member
export function createEmptyReport(staff: StaffMember, date: string): DailyReport {
  return {
    id: `${date}_${staff.id}`,
    date,
    staffId: staff.id,
    staffName: staff.name,
    department: staff.department,
    designation: staff.designation,
    deadline: '4:00 PM',
    complianceStatus: 'NOT SUBMITTED',
    priority: 'Normal',
    workDoneSummary: '',
    activitiesPerformed: '',
    issuesHeld: '',
    cashCollected: '',
    hasUnusualActivities: false,
    unusualActivityType: '',
    unusualActivitiesDetails: '',
    tasks: (staff.defaultKpis || []).map((kpi, idx) => ({
      id: `task-${idx + 1}`,
      kpi,
      description: '',
      status: 'Pending',
      kpiValue: '',
      keyAchievement: '',
    })),
    overallStatus: 'Pending',
    supportNeeded: false,
    supportDetails: '',
    challengeBlocker: '',
    priorityTomorrow: '',
    keyAchievementsSummary: '',
    updatedAt: new Date().toISOString(),
  };
}

